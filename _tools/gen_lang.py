def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    # Fabric 与 Forge 是两个独立模块，各自有 assets 拷贝，必须同时更新，
    # 否则 Forge 端会一直用旧文案（曾导致「取消」显示成键名 ains.restart_cancel）。
    outdirs = [
        os.path.join(root, "src", "main", "resources", "assets",
                     "mtr_no_original_trains", "lang"),
        os.path.join(root, "forge", "src", "main", "resources", "assets",
                     "mtr_no_original_trains", "lang"),
    ]
    for outdir in outdirs:
        os.makedirs(outdir, exist_ok=True)

    missing = [l for l in LANGS if l not in T]
    if missing:
        raise SystemExit("缺少翻译：" + ", ".join(missing))

    made = 0
    for lang in LANGS:
        vals = T[lang]
        keys = [
            "gui.mtr_no_original_trains.button",
            "gui.mtr_no_original_trains.title",
            "gui.mtr_no_original_trains.subtitle",
            "gui.mtr_no_original_trains.select_all",
            "gui.mtr_no_original_trains.select_none",
            "gui.mtr_no_original_trains.reset",
            "gui.mtr_no_original_trains.done",
            "gui.mtr_no_original_trains.expand",
            "gui.mtr_no_original_trains.collapse",
            "gui.mtr_no_original_trains.vehicles",
            "gui.mtr_no_original_trains.kept_summary",
            "gui.mtr_no_original_trains.restart_hint",
            "gui.mtr_no_original_trains.saved",
            "gui.mtr_no_original_trains.tooltip",
        ]
        data = dict(zip(keys, vals))
        # 选择界面底部的「取消」按钮。复用重启弹窗里第 6 个值（各语言的「取消」），
        # 这样 42 种语言都有本地化译文，不会退化成键名。
        rp = R.get(lang, R["en_us"])
        data["gui.mtr_no_original_trains.cancel"] = rp[5]
        # 重启确认弹窗的 6 个键（未单独翻译的语言用英文兜底）
        for k, v in zip(RESTART_KEYS, rp):
            data["gui.mtr_no_original_trains." + k] = v
        for outdir in outdirs:
            path = os.path.join(outdir, lang + ".json")
            with io.open(path, "w", encoding="utf-8", newline="\n") as f:
                json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
                f.write("\n")
        made += 1
    print("生成", made, "种语言 x", len(outdirs), "端 ->", outdirs[0])


if __name__ == "__main__":
    main()
